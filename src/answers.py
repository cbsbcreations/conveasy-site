def _swap(x, old, new):
    if isinstance(x, str):
        return x.replace(old, new)
    if isinstance(x, list):
        return [_swap(i, old, new) for i in x]
    if isinstance(x, tuple):
        return tuple(_swap(i, old, new) for i in x)
    if isinstance(x, dict):
        return {k: _swap(v, old, new) for k, v in x.items()}
    return x


